import { readFile, readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = resolve(frontendRoot, "../../content/included/poses");
const outputPath = resolve(
  frontendRoot,
  "web/src/lib/avatar/poses/pose_catalog.generated.json",
);
const webRequire = createRequire(
  new URL("../web/package.json", import.meta.url),
);

/** Project canonical Included documents verbatim; never resolve or author a second copy. */
export async function buildPoseProjection(root = sourceRoot) {
  const entries = (await readdir(root, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  if (!entries.length) throw new Error("Included Pose collection is empty");
  const poses = {};
  for (const entry of entries) {
    const document = JSON.parse(
      await readFile(join(root, entry, `${entry}.json`), "utf8"),
    );
    const pose = document.pose;
    if (
      document.schema_version !== 1 ||
      document.content_type !== "pose" ||
      !pose ||
      pose.schema !== "animaPose/1.0" ||
      typeof document.content_id !== "string" ||
      !document.content_id ||
      typeof document.name !== "string" ||
      !document.name ||
      pose.id !== document.content_id ||
      pose.name !== document.name ||
      "parent" in pose
    ) {
      throw new Error(`Invalid resolved Included Pose descriptor: ${entry}`);
    }
    if (Object.hasOwn(poses, pose.id))
      throw new Error(`Duplicate Included Pose id: ${pose.id}`);
    poses[pose.id] = pose;
  }
  const { default: prettier } = await import(
    pathToFileURL(webRequire.resolve("prettier")).href
  );
  return prettier.format(
    JSON.stringify({
      _generated:
        "Generated by pnpm poses:generate from content/included/poses; do not edit.",
      poses,
    }),
    { parser: "json" },
  );
}

/** A check is read-only and rejects missing/stale output instead of quietly repairing it. */
export async function generatePoseCatalog({
  root = sourceRoot,
  output = outputPath,
  check = true,
} = {}) {
  const expected = await buildPoseProjection(root);
  if (check) {
    let current;
    try {
      current = await readFile(output, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (current !== expected)
      throw new Error(
        "Pose projection drift; run pnpm poses:generate from src/frontend.",
      );
  } else {
    await writeFile(output, expected);
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !["--check", "--write"].includes(args[0])) {
    throw new Error(
      "Usage: node scripts/generate-pose-catalog.mjs --check|--write",
    );
  }
  await generatePoseCatalog({ check: args[0] === "--check" });
}
