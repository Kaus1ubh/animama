"""Opaque, owner-authorized package stages and bounded inspection lifetimes."""

from contextlib import AbstractContextManager
from typing import Any, BinaryIO, Protocol

from animama.app.contracts.content_package_staging import PartAck, StageKind, StageLimits, StageRecord, StageState
from animama.app.services.content_package_archive import InspectedPackage


class PackageStageLease(Protocol):
    """Exclusive cleanup exclusion until every byte reader and worker has finished.

    Writers reserve before growth. Sealing verifies exact bytes and makes them
    durable; reviewed bytes cannot change. Inspection has a separately bounded
    expansion budget. Neither the lease nor its metadata reveals an object key.
    """

    @property
    def record(self) -> StageRecord: ...
    def __enter__(self) -> "PackageStageLease": ...
    def __exit__(self, *_: object) -> None: ...
    def close(self) -> None: ...
    def discard(self) -> None: ...
    def set_state(self, state: StageState) -> StageRecord: ...
    def seal_archive(self) -> tuple[int, str]: ...
    def verify_archive(self) -> tuple[int, str]: ...
    def publish_review(self, review: dict[str, Any], review_digest: str) -> StageRecord: ...
    def renew_review(self, review_digest: str) -> StageRecord: ...
    def ensure_capacity(self, size: int) -> None: ...
    def open_archive(self) -> BinaryIO: ...
    def write_archive(self) -> AbstractContextManager[BinaryIO]: ...


class PackageStages(Protocol):
    """All operations authorize the owner, including replay, quota and cleanup.

    An account adapter declares owner_id. Locator and operation uniqueness are
    scoped to that identity; no request may select a different owner. Protected
    committing/recovery stages survive expiry until publication is reconciled.
    """

    limits: StageLimits

    def create_import(self, user_id: str, operation_id: str, filename: str, expected_bytes: int) -> StageRecord: ...
    def reserve_export(self, user_id: str, filename: str, expected_bytes: int) -> PackageStageLease: ...
    def acquire(
        self, user_id: str, stage_id: str, kind: StageKind = "import", *, allow_expired: bool = False
    ) -> PackageStageLease: ...
    def status(self, user_id: str, stage_id: str, kind: StageKind = "import") -> tuple[StageRecord, bool]: ...
    def find_import(self, user_id: str, operation_id: str) -> StageRecord | None: ...
    def append_part(self, user_id: str, stage_id: str, index: int, source: BinaryIO) -> PartAck: ...
    def discard(self, user_id: str, stage_id: str, kind: StageKind = "import") -> None: ...
    def sweep_expired(self, user_id: str | None = None) -> None: ...


class PackageInspector(Protocol):
    """Validate all archive facts and own bounded resources until context exit.

    Implementations must enforce the version-three parser, byte/digest/member,
    typed-document, capability, dependency and runtime budgets used by the local
    inspector. Storage adapters may use bounded temporary files for validation;
    installed storage locators must never be interpreted as host paths.
    """

    def inspect(self, lease: PackageStageLease) -> AbstractContextManager[InspectedPackage]: ...
